#!/usr/bin/env python3
import argparse
import base64
import datetime as dt
import json
import subprocess
from email.message import EmailMessage
from email.headerregistry import Address
import os
from html import escape

SIGNATURE = 'Kind regards,\n\nPrince S Mafinda\nOperations Manager\nNational Health Information Hub\nDirectorate of Policy, Planning and Information\nMinistry of Health'

SENDER = "nationalhealthinformationhub@gmail.com"
TOKEN = "/var/lib/nhih-monitor/oauth/token.json"

def query(sql, variables=None):
    cmd = ["psql", "-X", "-qAt", "-v", "ON_ERROR_STOP=1", "-d", "nhih"]
    for key, value in (variables or {}).items():
        cmd += ["-v", key + "=" + str(value)]
    return subprocess.run(cmd, input=sql, text=True, capture_output=True, check=True).stdout.strip()

def branded(row, overdue=False):
    tasks = row["tasks"]
    e = lambda v: escape(str(v), quote=True)
    count = lambda status: sum(t["status"] == status for t in tasks)
    intro = ("Please review the overdue assignments below and prioritise their resolution."
             if overdue else "Please find below a personalised overview of your outstanding assignments and operational priorities.")
    cards = []
    for t in tasks:
        progress = max(0, min(100, int(t["progress"] or 0)))
        color = "#b91c1c" if t["status"] == "overdue" else "#a16207" if t["status"] == "in_progress" else "#166534"
        cards.append(f"""<div style="border:1px solid #dce5e1;border-radius:8px;padding:16px;margin:12px 0">
        <strong style="color:{color}">{e(t['status'].replace('_',' ').title())}</strong><h3 style="margin:8px 0">{e(t['title'])}</h3>
        <p>Priority: {e(t['priority'].title())} &middot; Due: {e(t['due'])} GMT</p>
        <table role="presentation" width="100%" cellspacing="0" style="background:#e5e7eb"><tr><td width="{progress}%" bgcolor="{color}" height="8"></td><td></td></tr></table><p>Progress: {progress}%</p></div>""")
    return f"""<!doctype html><html><body style="margin:0;background:#f1f5f3;font-family:Arial,sans-serif;color:#18332d">
    <table role="presentation" width="100%" cellspacing="0"><tr><td align="center" style="padding:16px">
    <table role="presentation" width="100%" cellspacing="0" style="max-width:640px;background:white">
    <tr><td bgcolor="#103c35" style="padding:24px;color:white"><small>MINISTRY OF HEALTH | SIERRA LEONE</small><h1 style="font-size:24px">National Health Information Hub</h1>Operations Management &amp; Coordination</td></tr>
    <tr><td style="padding:24px"><small>OPERATIONAL BRIEFING | {dt.datetime.now(dt.timezone.utc):%d %B %Y}</small>
    <h2>Your Task &amp; Priority Briefing</h2><p>Dear {e(row['name'])},</p><p>{intro}</p>
    <table role="presentation" width="100%" style="background:#edf4f0;text-align:center"><tr><td style="padding:12px"><strong>{len(tasks)}</strong><br>Outstanding</td><td><strong>{count('in_progress')}</strong><br>In progress</td><td style="color:#b91c1c"><strong>{count('overdue')}</strong><br>Overdue</td></tr></table>
    <h2 style="font-size:19px">Your outstanding assignments</h2>{''.join(cards)}
    <h2 style="font-size:19px">Required action</h2><p>Kindly review your assignments, prioritise overdue deliverables and ensure your progress is accurately reflected on the NHIH Operations Dashboard. Where challenges or dependencies exist, please communicate them to Operations Management for timely support.</p>
    <p><a href="https://nhih-ops.tailecbac3.ts.net/" style="display:inline-block;background:#103c35;color:white;padding:14px 20px;text-decoration:none;border-radius:6px">Access NHIH Operations Dashboard</a></p>
    <p>Thank you for your continued commitment, professionalism and contribution towards the collective success of the Hub.</p>
    <p>{e(SIGNATURE).replace(chr(10),'<br>')}</p></td></tr>
    <tr><td bgcolor="#103c35" style="padding:20px;color:white;text-align:center">Accountability &middot; Collaboration &middot; Excellence<br><small>Automatically generated by the NHIH Operations Intelligence System on behalf of the Operations Manager.</small></td></tr>
    </table></td></tr></table></body></html>"""

def main():
    parser = argparse.ArgumentParser()
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--send", action="store_true")
    mode.add_argument("--test-to")
    mode.add_argument("--resend-overdue", action="store_true")
    mode.add_argument("--preview-overdue", action="store_true")
    args = parser.parse_args()
    today = dt.datetime.now(dt.timezone.utc).date()
    week = today - dt.timedelta(days=today.weekday())
    rows = json.loads(query("""
      SELECT COALESCE(json_agg(row_to_json(x)), '[]'::json) FROM (
        SELECT m.id, m.name, n.email, COALESCE(n.enabled,false) AS enabled,
          json_agg(json_build_object('title',t.title,'priority',t.priority,
          'due',to_char(t.due_date AT TIME ZONE 'UTC','YYYY-MM-DD HH24:MI'),
          'status',CASE WHEN t.due_date < now() THEN 'overdue' ELSE t.status END,
          'progress',t.progress) ORDER BY t.due_date) AS tasks
        FROM members m JOIN tasks t ON t.assigned_to::jsonb ? m.id
        LEFT JOIN member_notifications n ON n.member_id=m.id AND n.member_name=m.name
        WHERE t.status IN ('not_started','in_progress','under_review','overdue')
        GROUP BY m.id,m.name,n.email,n.enabled
      ) x;
    """))
    overdue = args.resend_overdue or args.preview_overdue
    if overdue:
        rows = [r for r in rows if any(t["status"] == "overdue" for t in r["tasks"])]
        for r in rows:
            r["tasks"] = [t for t in r["tasks"] if t["status"] == "overdue"]
    print(json.dumps({"members_with_pending_tasks":len(rows),
        "eligible":sum(bool(r["enabled"] and r["email"]) for r in rows),
        "mode":"overdue-resend" if args.resend_overdue else "live" if args.send else "test" if args.test_to else "preview"}))
    if not args.send and not args.test_to and not args.resend_overdue:
        return
    from google.oauth2.credentials import Credentials
    from google.auth.transport.requests import Request
    from googleapiclient.discovery import build
    creds = Credentials.from_authorized_user_file(TOKEN, ["https://www.googleapis.com/auth/gmail.send"])
    creds.refresh(Request())
    service = build("gmail","v1",credentials=creds,cache_discovery=False)
    def deliver(recipient, subject, body, html=None):
        msg = EmailMessage()
        msg["From"] = Address("NHIH Operations", addr_spec=SENDER)
        msg["To"] = Address(addr_spec=recipient)
        msg["Subject"] = subject
        msg.set_content(body)
        if html:
            msg.add_alternative(html, subtype="html")
        service.users().messages().send(userId="me",body={
            "raw":base64.urlsafe_b64encode(msg.as_bytes()).decode()
        }).execute(num_retries=0)
    if args.test_to:
        deliver(args.test_to, "[TEST] NHIH Weekly Task Reminder",
                "Illustrative test only. No real staff task details.\n\n" + SIGNATURE,
                branded({"name":"Test recipient","tasks":[{"title":"Illustrative assignment (test only)","priority":"high","status":"overdue","progress":65,"due":"2026-11-26 16:00"}]}))
        print("Test submitted")
        return
    failures = 0
    summary = []
    for row in rows:
        if not row["enabled"] or not row["email"]:
            summary.append(row["name"] + ": " + str(len(row["tasks"])) + " pending; not configured")
            continue
        params = {"week":week,"member":("overdue-resend:" + row["id"] if overdue else row["id"]),"count":len(row["tasks"])}
        claimed = query("""INSERT INTO notification_history(week_start,member_id,status,task_count)
          VALUES (:'week',:'member','sending',:'count')
          ON CONFLICT DO NOTHING RETURNING member_id;""",params)
        if not claimed:
            summary.append(row["name"] + ": already recorded; see delivery history")
            continue
        lines = ["Dear " + row["name"] + ",", "", "Please review your overdue assignments." if overdue else "Please review your outstanding tasks for this week.", ""]
        for i,t in enumerate(row["tasks"],1):
            lines.append(f"{i}. {t['title']} | {t['priority']} | {t['status']} | {t['progress']}% | Due: {t['due']} GMT")
        lines += ["","Please update your progress through the NHIH Operations Dashboard.",
                  "https://nhih-ops.tailecbac3.ts.net/", "", SIGNATURE]
        try:
            deliver(row["email"], "NHIH | Outstanding Tasks Requiring Attention" if overdue else "NHIH | Your Weekly Task & Operational Priorities", "\n".join(lines), branded(row, overdue))
            status = "submitted"
        except Exception:
            status = "uncertain"
            failures += 1
        query("""UPDATE notification_history SET status=:'status',updated_at=now()
          WHERE week_start=:'week' AND member_id=:'member';""",dict(params,status=status))
        print(row["id"] + ": " + status)
        summary.append(row["name"] + ": " + str(len(row["tasks"])) + " pending; " + status)
    manager = os.environ.get("NHIH_NOTIFICATION_MANAGER", "")
    if manager:
        params = {"week":week,"member":"__management_overdue_resend__" if overdue else "__management__","count":max(1,sum(len(r["tasks"]) for r in rows))}
        claimed = query("""INSERT INTO notification_history(week_start,member_id,status,task_count)
          VALUES (:'week',:'member','sending',:'count') ON CONFLICT DO NOTHING RETURNING member_id;""",params)
        if claimed:
            try:
                deliver(manager,"NHIH Overdue Resend Summary" if overdue else "NHIH Weekly Task Notification Summary",
                        "\n".join(["Weekly task reminder summary", "", *(summary or ["No pending tasks"])]))
                status = "submitted"
            except Exception:
                status = "uncertain"
                failures += 1
            query("""UPDATE notification_history SET status=:'status',updated_at=now()
              WHERE week_start=:'week' AND member_id=:'member';""",dict(params,status=status))
    if failures:
        raise SystemExit(1)

if __name__ == "__main__":
    main()
